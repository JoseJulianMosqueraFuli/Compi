def _copy_strength_detail_to_sets() -> None:
    """One strength_detail row becomes one exercise with ``sets`` identical sets."""
    bind = op.get_bind()
    rows = bind.execute(sa.select(_strength_detail).order_by(_strength_detail.c.id)).all()
    for row in rows:
        exercise_id = bind.execute(
            _workout_exercise.insert()
            .values(workout_id=row.workout_id, order_index=1, exercise_key=None, name=row.exercise)
            .returning(_workout_exercise.c.id)
        ).scalar_one()
        bind.execute(
            _exercise_set.insert(),
            [
                {'workout_exercise_id': exercise_id, 'order_index': i,
                 'reps': row.reps, 'weight_kg': row.weight_kg}
                for i in range(1, row.sets + 1)
            ],
        )


def _copy_sets_to_strength_detail() -> None:
    """Lossy: keep each workout's first exercise, its set count and its first set."""
    bind = op.get_bind()
    exercises = bind.execute(
        sa.select(_workout_exercise).order_by(
            _workout_exercise.c.workout_id, _workout_exercise.c.order_index
        )
    ).all()
    seen: set[int] = set()
    for ex in exercises:
        if ex.workout_id in seen:
            continue
        sets = bind.execute(
            sa.select(_exercise_set)
            .where(_exercise_set.c.workout_exercise_id == ex.id)
            .order_by(_exercise_set.c.order_index)
        ).all()
        if not sets:
            continue
        seen.add(ex.workout_id)
        bind.execute(
            _strength_detail.insert().values(
                workout_id=ex.workout_id, exercise=ex.name, sets=len(sets),
                reps=max(sets[0].reps, 1), weight_kg=sets[0].weight_kg,
            )
        )
